// Goal output: `Grade: B` when `score` is `85`.

const score = 85; // B
let grade = ""; // E

if (score >= 90) { // C
    grade = "A"; // F
} else if (score >= 80) { // A
    grade = "B"; // D
} else { // G
    grade = "C"; // H
} // I
console.log(`Grade: ${grade}`); // J

